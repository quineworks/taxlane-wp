'use strict';

// platform#2349 (part of platform#1943): pure derivation of
// site/public/status-feed.xml's content from status.json's `incidents`
// array (docs/product/status-page-rss-feed.md), so status.yml's automation
// can keep the feed paired with every status.json write instead of only
// ever writing status.json — which trips feed-drift-check.yml every run
// (scripts/feed-drift-check.cjs's status.json -> status-feed.xml pair).
// Same split as status-derive.cjs: pure logic here, fixture-tested by
// scripts/test-status-feed-derive.cjs, wired into status.yml's embedded
// script. Mirrors the render logic in site/public/status.html
// (componentNames(), formatDate() family, renderIncidents(), ~line
// 394-444) so the feed and the page never disagree on wording.

const CHANNEL_TITLE = 'Quine Works Status';
const CHANNEL_LINK = 'https://quineworks.com/status';
const CHANNEL_DESCRIPTION = 'Current status and incident history for TaxLane and quineworks.com.';
const SELF_LINK = 'https://quineworks.com/status-feed.xml';

function escapeXml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

// Same id -> name lookup componentNames() performs in status.html, falling
// back to the raw id if a component was ever removed from COMPONENTS.
function componentNames(componentIds, components) {
  const byId = new Map(components.map((c) => [c.id, c.name]));
  return (componentIds || []).map((id) => byId.get(id) || id).join(', ');
}

function itemXml(incident, components) {
  // ISO date of openedAt, matching status.html's own incident-history <li>
  // id and status-feed.xml's #{openedAt-as-ISO-date} <link>/<guid> anchor.
  const isoDate = incident.openedAt.slice(0, 10);
  const link = `${CHANNEL_LINK}#${isoDate}`;
  const names = componentNames(incident.components, components);
  // No outbound link to incident.url (the private tracking issue) anywhere
  // here -- platform#1951, same call status.html's own rendering already
  // made; url is dedup-only state, never read by this module.
  const description = incident.resolvedAt ? `${names} — resolved` : `${names} — ${incident.state}`;
  const pubDate = new Date(incident.resolvedAt || incident.openedAt).toUTCString();

  return [
    '    <item>',
    `      <title>${escapeXml(incident.title)}</title>`,
    `      <link>${escapeXml(link)}</link>`,
    `      <guid isPermaLink="false">${escapeXml(link)}</guid>`,
    `      <pubDate>${pubDate}</pubDate>`,
    `      <description>${escapeXml(description)}</description>`,
    '    </item>',
  ].join('\n');
}

// deriveStatusFeedXml({ incidents, components }) -> string
//
// incidents: status.json's `incidents[]` array (or deriveStatus()'s own
// output, same shape) -- { title, components: [id], state, openedAt,
// resolvedAt, url }.
//
// components: the COMPONENTS list ({ id, name }), status-derive.cjs's
// export, used to resolve incident.components ids to display names.
//
// Sort order matches status.html's renderIncidents(): by openedAt, most
// recent first -- not by pubDate, so a newly-resolved old incident doesn't
// jump to the top of either the page or the feed.
//
// Empty incidents -> zero <item> elements, still valid RSS (no placeholder
// fabricated), matching status.html's "No incidents reported." empty
// state.
function deriveStatusFeedXml({ incidents = [], components = [] }) {
  const sorted = incidents.slice().sort((a, b) => new Date(b.openedAt) - new Date(a.openedAt));
  const items = sorted.map((incident) => itemXml(incident, components));

  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Auto-generated by status.yml (platform#1943/#2349) from status.json — do not hand-edit. -->',
    '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">',
    '  <channel>',
    `    <title>${CHANNEL_TITLE}</title>`,
    `    <link>${CHANNEL_LINK}</link>`,
    `    <description>${escapeXml(CHANNEL_DESCRIPTION)}</description>`,
    '    <language>en</language>',
    `    <atom:link href="${SELF_LINK}" rel="self" type="application/rss+xml" />`,
    ...items,
    '  </channel>',
    '</rss>',
  ];
  return lines.join('\n') + '\n';
}

module.exports = { deriveStatusFeedXml, componentNames };
